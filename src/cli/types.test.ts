import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import ts from 'typescript';
import { describe, expect, it, vi } from 'vitest';

import type { CliIo } from './types.js';

import { EXIT, main, renderTypes } from './types.js';

const meta = { project: 'acme-ecom', environment: 'production', locale: 'en-US' };

const EXPECTED = `// Generated by @translifyhq/client types. Do not edit.
// acme-ecom / production / en-US — 2 keys
declare module '@translifyhq/client' {
  interface TranslifyKeys {
    'cart.title': string;
    'cart.totals.total': string;
  }
}
export {};
`;

const okResponse = (bundle: Record<string, string>): Response =>
  new Response(JSON.stringify(bundle), { status: 200, headers: { etag: '"e"' } });

interface Fake {
  io: CliIo;
  written: Map<string, string>;
  out: string[];
  err: string[];
  fetchFn: ReturnType<typeof vi.fn>;
}

const fake = (files: Record<string, string> = {}, env: Record<string, string> = {}): Fake => {
  const written = new Map<string, string>(Object.entries(files));
  const out: string[] = [];
  const err: string[] = [];
  const fetchFn = vi.fn();
  const io: CliIo = {
    env,
    fetch: fetchFn as unknown as typeof fetch,
    readFile: (path) => Promise.resolve(written.get(path)),
    writeFile: (path, text) => {
      written.set(path, text);

      return Promise.resolve();
    },
    stdout: (line) => {
      out.push(line);
    },
    stderr: (line) => {
      err.push(line);
    },
  };

  return { io, written, out, err, fetchFn };
};

const ARGS = ['--base-url', 'https://h/api', '--project', 'acme-ecom', '--environment', 'production', '--locale', 'en-US', '--out', 'src/keys.d.ts'];

describe('renderTypes', () => {
  it('is byte-exact for the spec example, keys sorted', () => {
    expect(renderTypes(meta, ['cart.totals.total', 'cart.title'])).toBe(EXPECTED);
  });

  it('escapes quotes and backslashes', () => {
    expect(renderTypes(meta, ["it's.ok", 'a\\b'])).toContain("    'a\\\\b': string;\n    'it\\'s.ok': string;\n");
  });

  it('counts one key in the singular', () => {
    expect(renderTypes(meta, ['a'])).toContain('— 1 key\n');
  });

  it('produces a file TypeScript parses without diagnostics', () => {
    const dir = mkdtempSync(join(tmpdir(), 'translify-types-'));
    const file = join(dir, 'keys.d.ts');
    writeFileSync(file, renderTypes(meta, ["it's.ok", 'a\\b', 'cart.title']));
    const program = ts.createProgram([file], { noEmit: true, strict: true, skipLibCheck: true, types: [] });
    const diagnostics = ts.getPreEmitDiagnostics(program).filter((d) => d.file?.fileName === file);
    expect(diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'))).toEqual([]);
  });
});

describe('main', () => {
  it('writes the file and reports the count', async () => {
    const { io, written, out, fetchFn } = fake();
    fetchFn.mockResolvedValueOnce(okResponse({ 'cart.totals.total': 'T', 'cart.title': 'C' }));

    const code = await main([...ARGS, '--key', 'pk_x'], io);

    expect(code).toBe(EXIT.ok);
    expect(written.get('src/keys.d.ts')).toBe(EXPECTED);
    expect(out).toEqual(['wrote src/keys.d.ts (2 keys)']);
    expect(fetchFn.mock.calls[0]?.[0]).toBe('https://h/api/delivery/acme-ecom/production/en-US?key=pk_x');
  });

  it('takes the key from TRANSLIFY_DELIVERY_KEY', async () => {
    const { io, fetchFn } = fake({}, { TRANSLIFY_DELIVERY_KEY: 'pk_env' });
    fetchFn.mockResolvedValueOnce(okResponse({ a: 'b' }));
    expect(await main(ARGS, io)).toBe(EXIT.ok);
    expect(fetchFn.mock.calls[0]?.[0]).toContain('key=pk_env');
  });

  it.each([
    ['missing --out', ARGS.filter((a, i) => a !== '--out' && ARGS[i - 1] !== '--out')],
    ['missing key', ARGS],
    ['sk_ key', [...ARGS, '--key', 'sk_x']],
    ['unknown flag', [...ARGS, '--key', 'pk_x', '--bogus']],
    ['bad base url', [...ARGS.map((a) => (a === 'https://h/api' ? 'h/api' : a)), '--key', 'pk_x']],
  ])('usage error: %s → 2 with a message and usage on stderr', async (_label, argv) => {
    const { io, err, fetchFn } = fake();
    expect(await main(argv, io)).toBe(EXIT.usage);
    expect(fetchFn).not.toHaveBeenCalled();
    expect(err.join('\n')).toMatch(/--base-url/);
    expect(err.join('\n')).not.toContain('sk_x');
  });

  it('unions and sorts keys across namespaces, one request each', async () => {
    const { io, written, fetchFn } = fake();
    fetchFn.mockImplementation((url: string) =>
      Promise.resolve(
        url.includes('namespace=cart') ? okResponse({ 'cart.b': 'x', 'cart.a': 'y' }) : okResponse({ 'checkout.a': 'z' }),
      ),
    );

    const code = await main([...ARGS, '--key', 'pk_x', '--namespace', 'cart', '--namespace', 'checkout'], io);

    expect(code).toBe(EXIT.ok);
    expect(fetchFn).toHaveBeenCalledTimes(2);
    expect(written.get('src/keys.d.ts')).toContain("    'cart.a': string;\n    'cart.b': string;\n    'checkout.a': string;\n");
  });

  it('empty bundle → 3 with a message naming project, environment and locale', async () => {
    const { io, err, written, fetchFn } = fake();
    fetchFn.mockResolvedValueOnce(okResponse({}));
    expect(await main([...ARGS, '--key', 'pk_x'], io)).toBe(EXIT.delivery);
    expect(err).toEqual(['error: no published keys for acme-ecom/production/en-US']);
    expect(written.has('src/keys.d.ts')).toBe(false);
  });

  it('404 → 3 with the delivery message on stderr', async () => {
    const { io, err, fetchFn } = fake();
    fetchFn.mockResolvedValueOnce(new Response(null, { status: 404 }));
    expect(await main([...ARGS, '--key', 'pk_x'], io)).toBe(EXIT.delivery);
    expect(err).toEqual(['error: project, environment or locale not found, or nothing published']);
  });

  it('fetch rejection → 4', async () => {
    const { io, err, fetchFn } = fake();
    fetchFn.mockRejectedValueOnce(new TypeError('offline'));
    expect(await main([...ARGS, '--key', 'pk_x'], io)).toBe(EXIT.network);
    expect(err).toEqual(['error: network error: offline']);
  });

  it('--check: identical → 0 and no write', async () => {
    const { io, written, out, fetchFn } = fake({ 'src/keys.d.ts': EXPECTED });
    fetchFn.mockResolvedValueOnce(okResponse({ 'cart.totals.total': 'T', 'cart.title': 'C' }));
    const writeSpy = vi.spyOn(io, 'writeFile');
    expect(await main([...ARGS, '--key', 'pk_x', '--check'], io)).toBe(EXIT.ok);
    expect(writeSpy).not.toHaveBeenCalled();
    expect(written.get('src/keys.d.ts')).toBe(EXPECTED);
    expect(out).toEqual([]);
  });

  it('--check: different → 1 and no write', async () => {
    const { io, written, err, fetchFn } = fake({ 'src/keys.d.ts': 'stale' });
    fetchFn.mockResolvedValueOnce(okResponse({ a: 'b' }));
    expect(await main([...ARGS, '--key', 'pk_x', '--check'], io)).toBe(EXIT.drift);
    expect(written.get('src/keys.d.ts')).toBe('stale');
    expect(err).toEqual(['src/keys.d.ts is out of date; run without --check']);
  });

  it('--check: missing file → 1', async () => {
    const { io, fetchFn } = fake();
    fetchFn.mockResolvedValueOnce(okResponse({ a: 'b' }));
    expect(await main([...ARGS, '--key', 'pk_x', '--check'], io)).toBe(EXIT.drift);
  });

  it('--help prints usage to stdout and returns 0', async () => {
    const { io, out, fetchFn } = fake();
    expect(await main(['--help'], io)).toBe(EXIT.ok);
    expect(out.join('\n')).toMatch(/--base-url/);
    expect(out.join('\n')).toMatch(/TRANSLIFY_DELIVERY_KEY/);
    expect(fetchFn).not.toHaveBeenCalled();
  });
});

describe('main (review fixes)', () => {
  it('accepts the documented leading "types" word', async () => {
    const { io, written, fetchFn } = fake();
    fetchFn.mockResolvedValueOnce(okResponse({ a: 'b' }));
    expect(await main(['types', ...ARGS, '--key', 'pk_x'], io)).toBe(EXIT.ok);
    expect(written.has('src/keys.d.ts')).toBe(true);
  });

  it('"types --help" prints usage', async () => {
    const { io, out } = fake();
    expect(await main(['types', '--help'], io)).toBe(EXIT.ok);
    expect(out.join('\n')).toMatch(/--base-url/);
  });

  it('normalises a trailing slash on --base-url like the library does', async () => {
    const { io, fetchFn } = fake();
    fetchFn.mockResolvedValueOnce(okResponse({ a: 'b' }));
    const argv = ARGS.map((a) => (a === 'https://h/api' ? 'https://h/api/' : a));
    expect(await main([...argv, '--key', 'pk_x'], io)).toBe(EXIT.ok);
    expect(fetchFn.mock.calls[0]?.[0]).toBe('https://h/api/delivery/acme-ecom/production/en-US?key=pk_x');
  });
});

describe('main (deferred minors)', () => {
  it('a stray positional is refused without echoing it, since it may be the key', async () => {
    const { io, err } = fake();
    expect(await main(['pk_s3cret', ...ARGS], io)).toBe(EXIT.usage);
    expect(err[0]).toBe('error: unexpected argument; the key goes in --key or TRANSLIFY_DELIVERY_KEY');
    expect(err.join('\n')).not.toContain('pk_s3cret');
  });

  it('an unknown option is named, a key inside it is redacted', async () => {
    const { io, err } = fake();
    expect(await main([...ARGS, '--key=pk_s3cret', '--kye', 'x'], io)).toBe(EXIT.usage);
    expect(err[0]).toBe("error: Unknown option '--kye'");
    expect(await main([...ARGS, '--kye=pk_s3cret'], io)).toBe(EXIT.usage);
    expect(err.join('\n')).not.toContain('pk_s3cret');
  });

  it('a failure that is not a TranslifyError is reported as NETWORK with the key redacted', async () => {
    const { io, err, fetchFn } = fake();
    fetchFn.mockResolvedValueOnce({ status: 200, text: () => Promise.resolve('{}'), headers: { get: () => { throw new Error('headers broke pk_s3cret'); } } });
    expect(await main([...ARGS, '--key', 'pk_s3cret'], io)).toBe(EXIT.network);
    expect(err).toEqual(['error: network error: headers broke [key]']);
  });
});
