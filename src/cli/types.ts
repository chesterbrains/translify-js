import { parseArgs } from 'node:util';

import { TranslifyError } from '../errors.js';
import { fetchEntry } from '../fetcher.js';
import { resolveOptions } from '../options.js';
import { entryRef } from '../url.js';

export const EXIT = { ok: 0, drift: 1, usage: 2, delivery: 3, network: 4 } as const;

export interface CliIo {
  env: Record<string, string | undefined>;
  fetch: typeof fetch;
  /** `undefined` when the file does not exist. */
  readFile(path: string): Promise<string | undefined>;
  writeFile(path: string, text: string): Promise<void>;
  stdout(line: string): void;
  stderr(line: string): void;
}

export const USAGE = `Usage: translify-client types --base-url <url> --project <slug> --environment <slug> --locale <code> --out <file>
                              [--namespace <ns>]... [--key <pk_...>] [--check]

Generates a TypeScript declaration that types every published key of one locale.

  --base-url      API origin including /api, e.g. https://translify.example/api (required)
  --project       project slug (required)
  --environment   environment slug (required)
  --locale        locale whose key set defines the app, usually the source locale (required)
  --out           file to write, e.g. src/translify-keys.d.ts (required)
  --namespace     only this namespace; repeat for several (default: whole locale)
  --key           publishable delivery key; default: TRANSLIFY_DELIVERY_KEY
  --check         write nothing; exit 1 when the file on disk differs
  --help          this text

Exit codes: 0 ok, 1 out of date (--check), 2 usage, 3 delivery refused, 4 network.`;

interface Meta {
  project: string;
  environment: string;
  locale: string;
}

const quote = (key: string): string => `'${key.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** Deterministic: byte-sorted keys, LF, trailing newline. */
export const renderTypes = (meta: Meta, keys: readonly string[]): string => {
  const sorted = [...keys].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const count = `${sorted.length} ${sorted.length === 1 ? 'key' : 'keys'}`;
  const lines = sorted.map((key) => `    ${quote(key)}: string;`);

  return [
    '// Generated by @translifyhq/client types. Do not edit.',
    `// ${meta.project} / ${meta.environment} / ${meta.locale} — ${count}`,
    "declare module '@translifyhq/client' {",
    '  interface TranslifyKeys {',
    ...lines,
    '  }',
    '}',
    'export {};',
    '',
  ].join('\n');
};

interface Parsed {
  baseUrl: string;
  project: string;
  environment: string;
  locale: string;
  out: string;
  namespaces: string[] | undefined;
  key: string;
  check: boolean;
}

class UsageError extends Error {}

const parse = (argv: string[], env: CliIo['env']): Parsed | 'help' => {
  let values: Record<string, string | boolean | string[] | undefined>;
  try {
    ({ values } = parseArgs({
      args: argv,
      strict: true,
      allowPositionals: false,
      options: {
        'base-url': { type: 'string' },
        project: { type: 'string' },
        environment: { type: 'string' },
        locale: { type: 'string' },
        out: { type: 'string' },
        namespace: { type: 'string', multiple: true },
        key: { type: 'string' },
        check: { type: 'boolean' },
        help: { type: 'boolean' },
      },
    }));
  } catch (error) {
    throw new UsageError(error instanceof Error ? error.message : String(error));
  }
  if (values.help === true) return 'help';

  const text = (name: string): string => {
    const value = values[name];
    if (typeof value !== 'string' || value.trim() === '') throw new UsageError(`--${name} is required`);

    return value.trim();
  };
  const key = typeof values.key === 'string' && values.key !== '' ? values.key : env.TRANSLIFY_DELIVERY_KEY;
  if (key === undefined || key.trim() === '') throw new UsageError('a delivery key is needed: --key or TRANSLIFY_DELIVERY_KEY');
  const namespaces = Array.isArray(values.namespace) ? values.namespace : undefined;

  return {
    baseUrl: text('base-url'),
    project: text('project'),
    environment: text('environment'),
    locale: text('locale'),
    out: text('out'),
    namespaces,
    key: key.trim(),
    check: values.check === true,
  };
};

export const main = async (argv: string[], io: CliIo): Promise<number> => {
  let parsed: Parsed;
  try {
    const result = parse(argv, io.env);
    if (result === 'help') {
      io.stdout(USAGE);

      return EXIT.ok;
    }
    parsed = result;
    // Reuse the library's validation so the CLI refuses exactly what the client refuses.
    resolveOptions({ ...parsed, fetch: io.fetch });
  } catch (error) {
    io.stderr(`error: ${error instanceof Error ? error.message : String(error)}`);
    io.stderr(USAGE);

    return EXIT.usage;
  }

  const keys = new Set<string>();
  try {
    for (const namespace of parsed.namespaces ?? [undefined]) {
      const ref = entryRef(parsed, parsed.locale, namespace);
      const outcome = await fetchEntry(io.fetch, ref.url, undefined, new AbortController().signal);
      if (outcome.kind === 'fresh') for (const key of Object.keys(outcome.entry.bundle)) keys.add(key);
    }
  } catch (error) {
    const failure = error instanceof TranslifyError ? error : new TranslifyError('NETWORK', String(error));
    io.stderr(`error: ${failure.message}`);

    return failure.code === 'NETWORK' ? EXIT.network : EXIT.delivery;
  }

  if (keys.size === 0) {
    io.stderr(`error: no published keys for ${parsed.project}/${parsed.environment}/${parsed.locale}`);

    return EXIT.delivery;
  }

  const rendered = renderTypes(parsed, [...keys]);
  if (parsed.check) {
    if ((await io.readFile(parsed.out)) === rendered) return EXIT.ok;
    io.stderr(`${parsed.out} is out of date; run without --check`);

    return EXIT.drift;
  }

  await io.writeFile(parsed.out, rendered);
  io.stdout(`wrote ${parsed.out} (${keys.size} ${keys.size === 1 ? 'key' : 'keys'})`);

  return EXIT.ok;
};
