#!/usr/bin/env bash
# Packs the package and installs the tarball into a scratch project: ESM import, CJS require
# and the bin must all work from a consumer's point of view.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

tgz="$(cd "$root" && pnpm pack --pack-destination "$tmp" 2>/dev/null | tail -1)"
cd "$tmp"
npm init -y >/dev/null
npm install --silent --no-audit --no-fund "$tgz" >/dev/null

node --input-type=module -e "import('@translifyhq/client').then((m) => { if (typeof m.createTranslify !== 'function' || typeof m.localStorageStorage !== 'function') process.exit(1); })"
node -e "const m = require('@translifyhq/client'); if (typeof m.createTranslify !== 'function' || typeof m.TranslifyError !== 'function') process.exit(1)"
npx translify-client types --help | grep -q -- '--base-url'
npx translify-client --help | grep -q -- '--base-url'
test -f node_modules/@translifyhq/client/dist/index.d.ts

# Consumer-level typing: a generated keys file must narrow TranslifyKey for a project that
# resolves the published package (not the repo's own sources). The @ts-expect-error line fails
# the compile when the augmentation stops narrowing.
cat > keys.d.ts <<'DTS'
// Generated by @translifyhq/client types. Do not edit.
// acme-ecom / production / en-US — 1 key
declare module '@translifyhq/client' {
  interface TranslifyKeys {
    'cart.title': string;
  }
}
export {};
DTS
cat > consumer.ts <<'TS'
import { createTranslify, type TranslifyKey } from '@translifyhq/client';

const known: TranslifyKey = 'cart.title';
const client = createTranslify({ baseUrl: 'https://h/api', project: 'p', environment: 'e', key: 'pk_x' });
client.get('en-US', known);
// @ts-expect-error an undeclared key is refused once TranslifyKeys is augmented
client.get('en-US', 'cart.nope');
TS
node "$root/node_modules/typescript/bin/tsc" --noEmit --strict --module nodenext --moduleResolution nodenext --target es2022 --lib es2022,dom keys.d.ts consumer.ts
# Without the augmentation the same consumer must fail: proves the check is live.
if node "$root/node_modules/typescript/bin/tsc" --noEmit --strict --module nodenext --moduleResolution nodenext --target es2022 --lib es2022,dom consumer.ts >/dev/null 2>&1; then
  echo "augmentation check is inert: consumer.ts compiled without keys.d.ts" >&2
  exit 1
fi

echo "pack smoke ok"
